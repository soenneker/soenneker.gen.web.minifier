using Microsoft.CodeAnalysis;

namespace Soenneker.Gen.Web.Minifier;

[Generator]
public sealed class WebMinifierGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
        {
            ctx.AddSource("Generated.g.cs", "// Generated by Soenneker.Gen.Web.Minifier" + "\n");
        });
    }
}
